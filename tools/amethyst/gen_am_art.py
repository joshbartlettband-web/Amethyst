"""Amethyst's pictures for the FM-1 (firmware/src/amethyst.c): each stage's photo at 240 x 240 in its own 16 colors,
and the moss that crawls over it at 120 x 120 (drawn at 2 x) in 15 colors and see-through. 4 bits a pixel, packed in
bands of 16 rows with dsp.c lz_unpack's format (tools/gen_tables.py lz_pack), into the resource region
(MELODEE_RES). The firmware unpacks each picture once, into the pool.

  tools/amethyst/gen_am_art.py build/gen/am_art.h

The photos are docs/amethyst/gemini/ (see PROMPTS.md there for where each came from and its license)."""
import sys
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "tools"))
from gen_tables import lz_pack  # noqa: E402

SRC = ROOT / "docs" / "amethyst" / "gemini"
# colors every stage's palette keeps (violet, light violet, moss, light moss, sodium, the aerial's red)
KEEP = [(138, 82, 210), (206, 172, 248), (84, 112, 44), (150, 182, 82), (226, 140, 48), (255, 60, 70)]
STAGES = [("END", "the-end-moss.jpg")]
BAND = 16


def nearest(px, pal):
    best, bi = 1 << 30, 0
    for i, (r, g, b) in enumerate(pal):
        d = (px[0] - r) ** 2 + (px[1] - g) ** 2 + (px[2] - b) ** 2
        if d < best:
            best, bi = d, i
    return bi


def palette(img, n, keep):
    q = img.quantize(colors=n - len(keep), method=Image.Quantize.MEDIANCUT, dither=Image.Dither.NONE)
    flat = q.getpalette()[:3 * (n - len(keep))]
    pal = [tuple(flat[i:i + 3]) for i in range(0, len(flat), 3)] + keep
    pal.sort(key=lambda c: c[0] * 3 + c[1] * 6 + c[2])        # darkest first
    return pal


def pack4(rows):
    out = bytearray()
    for row in rows:
        for x in range(0, len(row), 2):
            out.append(row[x] << 4 | row[x + 1])
    return bytes(out)


def bands(idx, w, h):
    data, at = bytearray(), []
    for y0 in range(0, h, BAND):
        at.append(len(data))
        data += lz_pack(pack4(idx[y0:y0 + BAND]))
    at.append(len(data))
    return bytes(data), at


def photo(name):
    img = Image.open(SRC / name).convert("RGB")
    w, h = img.size
    s = min(w, h)
    img = img.crop(((w - s) // 2, (h - s) // 2, (w - s) // 2 + s, (h - s) // 2 + s)).resize((240, 240), Image.LANCZOS)
    pal = palette(img, 16, KEEP)
    px = img.load()
    cache, idx = {}, []
    for y in range(240):
        row = []
        for x in range(240):
            p = px[x, y]
            if p not in cache:
                cache[p] = nearest(p, pal)
            row.append(cache[p])
        idx.append(row)
    return pal, idx


def moss():
    img = Image.open(SRC / "layer-moss.jpg").convert("RGB")
    w, h = img.size
    img = img.crop((40, 40, w - 40, h - 40)).resize((120, 120), Image.LANCZOS)
    raw = img.tobytes()
    lum = [0.3 * raw[i] + 0.59 * raw[i + 1] + 0.11 * raw[i + 2] for i in range(0, len(raw), 3)]
    pal = palette(img, 15, KEEP[:4])
    pal = [(0, 0, 0)] + pal                                     # index 0: see-through
    px, idx = img.load(), []
    for y in range(120):
        row = []
        for x in range(120):
            row.append(0 if lum[y * 120 + x] < 26 else 1 + nearest(px[x, y], pal[1:]))
        idx.append(row)
    return pal, idx


def c_bytes(name, data, attr=""):
    lines = [f"static const uint8_t {name}[{len(data)}]{attr} = {{"]
    for i in range(0, len(data), 32):
        lines.append("    " + ",".join(map(str, data[i:i + 32])) + ",")
    return lines + ["};"]


def main():
    out = Path(sys.argv[1])
    lines = ["/* Generated by tools/amethyst/gen_am_art.py: Amethyst's pictures (amethyst.c). */", "#pragma once",
             "#ifndef MELODEE_RES", "#define MELODEE_RES", "#endif", f"#define AM_BAND {BAND}u"]
    total = 0
    for tag, name in STAGES:
        pal, idx = photo(name)
        data, at = bands(idx, 240, 240)
        total += len(data)
        lines.append(f"/* {name}: 240 x 240, {len(data)} bytes */")
        lines.append(f"static const uint8_t AM_{tag}_PAL[48] = {{" + ",".join(str(v) for c in pal for v in c) + "};")
        lines.append(f"static const uint16_t AM_{tag}_AT[{len(at)}] = {{" + ",".join(map(str, at)) + "};")
        lines += c_bytes(f"AM_{tag}_LZ", data, " MELODEE_RES")
    pal, idx = moss()
    data, at = bands(idx, 120, 120)
    total += len(data)
    lines.append(f"/* layer-moss.jpg: 120 x 120, index 0 see-through, {len(data)} bytes */")
    lines.append("static const uint8_t AM_MOSS_PAL[48] = {" + ",".join(str(v) for c in pal for v in c) + "};")
    lines.append(f"static const uint16_t AM_MOSS_AT[{len(at)}] = {{" + ",".join(map(str, at)) + "};")
    lines += c_bytes("AM_MOSS_LZ", data, " MELODEE_RES")
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(lines) + "\n")
    print(f"amethyst art: {len(STAGES)} stage(s) and the moss, {total} B -> {out}")


if __name__ == "__main__":
    main()
